const baseTimeline = (createdAt, status, deptIds, actor = '系统') => {
  const timeline = [
    {
      id: `tl-${createdAt}-1`,
      type: 'created',
      title: '诉求已提交',
      desc: 'AI 已完成初步识别，等待辅导员审核',
      at: createdAt,
      actor: '学生',
    },
    {
      id: `tl-${createdAt}-2`,
      type: 'ai',
      title: 'AI 完成要素提取',
      desc: '已生成标准化工单草稿，并完成风险扫描',
      at: plus(createdAt, 1),
      actor: '智汇中枢',
    },
  ]
  if (status !== 'pending_review') {
    timeline.push({
      id: `tl-${createdAt}-3`,
      type: 'assigned',
      title: '辅导员审核通过',
      desc: `已分派至 ${deptIds.map((id) => departmentMap[id]?.short || id).join('、')}`,
      at: plus(createdAt, 8),
      actor: '陈予安',
    })
  }
  if (['processing', 'awaiting_confirm', 'completed'].includes(status)) {
    timeline.push({
      id: `tl-${createdAt}-4`,
      type: 'accepted',
      title: '经办部门已接单',
      desc: '工单进入处理队列，按 SLA 时限推进',
      at: plus(createdAt, 21),
      actor: deptIds[0] ? departmentMap[deptIds[0]]?.short : '经办部门',
    })
  }
  if (['awaiting_confirm', 'completed'].includes(status)) {
    timeline.push({
      id: `tl-${createdAt}-5`,
      type: 'awaiting_confirm',
      title: '处置完成，等待学生确认',
      desc: '经办部门已回传处理结果与佐证材料',
      at: plus(createdAt, 74),
      actor: deptIds[0] ? departmentMap[deptIds[0]]?.short : '经办部门',
    })
  }
  if (status === 'completed') {
    timeline.push({
      id: `tl-${createdAt}-6`,
      type: 'completed',
      title: '学生确认办结',
      desc: '工单已归档，纳入部门办理数据统计',
      at: plus(createdAt, 102),
      actor: '学生',
    })
  }
  return timeline
}

